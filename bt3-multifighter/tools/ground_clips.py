# ------------------------------------------------------------------------------------------ quaternions

def qmul(a, b):
    ax, ay, az, aw = a; bx, by, bz, bw = b
    return (aw*bx + ax*bw + ay*bz - az*by, aw*by - ax*bz + ay*bw + az*bx,
            aw*bz + ax*by - ay*bx + az*bw, aw*bw - ax*bx - ay*by - az*bz)


def qconj(q):
    return (-q[0], -q[1], -q[2], q[3])


def qnorm(q):
    n = math.sqrt(sum(v*v for v in q))
    return tuple(v/n for v in q)


def qaxis(axis, degrees):
    half = math.radians(degrees)/2
    s = math.sin(half)
    return (axis[0]*s, axis[1]*s, axis[2]*s, math.cos(half))


def qrot(q, v):
    return qmul(qmul(q, (v[0], v[1], v[2], 0.0)), qconj(q))[:3]


def encode_quat(q):
    """Native packed quaternion (256E00): the largest component is dropped (made positive), the other three are
    20-bit fixed point in [-1/sqrt2, 1/sqrt2]."""
    q = qnorm(q)
    i = max(range(4), key=lambda k: (abs(q[k]), -k))
    if q[i] < 0: q = tuple(-v for v in q)
    scale, root2 = 9.536752259009518e-7, 1.4142135381698608
    packed = i << 60
    for k, v in enumerate(q[j] for j in range(4) if j != i):
        raw = int(math.floor((v/root2 + .5)/scale + .5))
        packed |= max(0, min(0xFFFFF, raw)) << (20*k)
    return packed


