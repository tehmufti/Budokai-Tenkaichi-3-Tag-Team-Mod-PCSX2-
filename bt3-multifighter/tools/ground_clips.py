def ease(points, x):
    """Cosine-eased piecewise curve through (x, y) points sorted by x, for x in [points[0].x, points[-1].x]."""
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        if x <= x1:
            u = 0.0 if x1 == x0 else (x - x0)/(x1 - x0)
            return y0 + (y1 - y0)*(1 - math.cos(math.pi*u))/2
    return points[-1][1]


def smooth(u):
    u = min(1.0, max(0.0, u))
    return u*u*(3 - 2*u)


def thigh_angle(gait, q):
    """Thigh angle (degrees, positive = forward) at leg phase q: linear through the stance, eased through the swing."""
    if q <= STANCE[gait]:
        return SWEEP[gait]*(1 - 2*q/STANCE[gait])
    return ease(CURVES[gait]['thigh'], q)


def arm_phase(gait, q):
    """Smooth counter-swing synchronized to contact and toe-off, without following the knee's recovery kick.

    Both halves meet with zero angular velocity. In the old clip the arms followed the thigh's overshoot and
    could suddenly snap backwards as the foot recovered; the reference keeps the elbows bent and pumps smoothly.
    """
    stance = STANCE[gait]
    return (math.cos(math.pi*q/stance) if q <= stance else
            -math.cos(math.pi*(q - stance)/(1 - stance)))


def gait_pose(gait, phase, amp=1.0):
    """Deltas {bone: [(frame, axis, degrees), ...]} of one gait at cycle phase 0..1 (right leg phase), amplitude
    0..1. frame is the bone whose posed orientation the axis is given in (None: model space)."""
    c = CURVES[gait]
    d = {}
    swing = {}
    for side, (thigh, knee, ankle) in LEGS.items():
        q = (phase + (0.0 if side == 'R' else 0.5)) % 1.0
        t, k, foot = thigh_angle(gait, q), ease(c['knee'], q), ease(c['ankle'], q)
        d[thigh] = [(PELVIS, (1, 0, 0), -amp*t)]
        d[knee] = [(PELVIS, (1, 0, 0), amp*k)]
        d[ankle] = [(PELVIS, (1, 0, 0), amp*(t - k + foot))]
        swing[side] = arm_phase(gait, q)
    lean16, lean17 = c['lean']
    d[PELVIS] = [(None, (0, 1, 0), -amp*c['pelvis']*swing['R'])]
    d[SPINE] = [(PELVIS, (1, 0, 0), amp*lean16), (None, (0, 1, 0), amp*c['pelvis']*swing['R'])]
    d[CHEST] = [(SPINE, (1, 0, 0), amp*lean17), (None, (0, 1, 0), amp*c['chest']*swing['R'])]
    # The gaze stays forward while the chest counter-rotates, instead of yawing with every footfall.
    d[NECK] = [(CHEST, (1, 0, 0), amp*c['head']/2), (None, (0, 1, 0), -amp*c['chest']*swing['R']/2)]
    d[HEAD] = [(NECK, (1, 0, 0), amp*c['head']/2), (None, (0, 1, 0), -amp*c['chest']*swing['R']/2)]
    elbow_rest, elbow_run = c['elbow']
    for side, (shoulder, elbow, _) in ARMS.items():
        down = c['arm_down']*(-1 if side == 'R' else 1)
        # Arms swing against the same-side leg; positive X swings an arm back.
        arm = amp*(c['arm_swing']*swing[side] - c['arm_forward'])
        d[shoulder] = [(CHEST, (0, 0, 1), down), (CHEST, (1, 0, 0), arm)]
        d[elbow] = [(CHEST, (1, 0, 0), -(elbow_rest + amp*(elbow_run - elbow_rest)))]
    return d


def stop_pose(u):
    """The brake at u = 0..1 of the stop clip: the right foot planted ahead and braced, the left trailing, the body
    leaning back; it settles to standing (arms down, legs straight) by the end."""
