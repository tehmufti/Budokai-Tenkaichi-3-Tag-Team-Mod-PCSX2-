# ------------------------------------------------------------------------------------------ developer modes (ISO)

def _developer_module(name):
    """model_assets / model_animations, for the developer modes below only. Imported by name so that the player payload's
    import closure (build_player_bundle.closure follows every import statement) does not ship these modder tools: the
    match-time path (build_set, the clip constants) never needs them."""
    import importlib
    return importlib.import_module(name)


def rotated_bones(clips=None):
    """Bones 1..54 whose rotation differs from rest (identity) in some clip, with all their ancestors."""
    an = _developer_module('model_animations')
    clips = build_set() if clips is None else clips
    out = set()
    for data in clips.values():
        clip = an.AnimationClip.from_decoded(0, an.decompress_animation(data))
        for track in clip.tracks:
            if any(abs(k.rotation[3]) < 1 - 1e-6 for k in track.keys): out.add(track.bone_id)
    for bone in list(out):
        while PARENTS[bone] > 0:
            bone = PARENTS[bone]
            out.add(bone)
    return out


def compatible(parents, rotated=None):
    """(True, []) when a skeleton ({bone: parent}) poses like the standard biped under these clips: for every
    rotated bone it has, the nearest ancestor at or below 54 is PARENTS[bone] (bones above 54 in between never
    animate, so they only lengthen a chain). Bones the clips keep at rest may hang anywhere."""
    rotated = rotated_bones() if rotated is None else rotated
    bad = []
    for bone in sorted(rotated):
        if bone not in parents: continue
        q = parents[bone]
        while q > 54 and q in parents: q = parents[q]
        if q != PARENTS[bone]: bad.append(bone)
    return not bad, bad


def pmdl_parents(geometry):
    """{bone: parent} of a native PMDL skeleton (the part stack of 24C... model loading, as model_assets)."""
    if geometry[:4] != b'pmdl': raise ValueError('Expected native PMDL geometry')
    count, offset = struct.unpack_from('<I', geometry, 8)[0], struct.unpack_from('<I', geometry, 108)[0]
    stack, parents = [], {}
    for _ in range(count):
        size, pop, _, _, bone = struct.unpack_from('<IHHHH', geometry, offset)
        if size == 0: break      # some BT4 models end their part list early
        if size < 64: raise ValueError('Invalid skeleton part')
        parents[bone] = stack[-1] if stack else -1
        stack.append(bone)
        if pop: del stack[-pop:]
        offset += size
    return parents


def skeleton_parents(iso, character):
    """{bone: parent} of a character's base model on this tree's disc (BT4: bt4_resources' file numbering)."""
    ma = _developer_module('model_assets')
    try:
        import bt4_resources
        mesh = bt4_resources.request_files(character)[0]
    except ImportError:
        mesh = 10*character + 1424
    return pmdl_parents(ma.package_entry(ma.read_archive_entry(iso, mesh), 3))


def scan_parents(iso, characters):
    """{character: (compatible, bad bones) or an error string} for every readable character slot."""
    rotated = rotated_bones()
    out = {}
    for ch in characters:
        try:
            parents = skeleton_parents(iso, ch)
        except Exception as error:  # noqa: BLE001 - empty or menu-only slot
            out[ch] = repr(error)[:90]
            continue
        out[ch] = compatible(parents, rotated)
    return out


def extract_fist(iso, character=0, anim=3):
    ma = _developer_module('model_assets')
    an = _developer_module('model_animations')
    clip = an.AnimationBank.from_bytes(ma.read_animation_bank(iso, character)).clip(anim)
    pose = clip.evaluate(0)
    return {b: tuple(round(v, 6) if abs(v) > 2e-6 else 0.0 for v in pose[b].rotation) for b in FIST}


def render(iso, characters, out_dir, columns=8, size=180, keys=None, views=('side', 'front'), zoom=1.0):
    """Contact sheets (side and front views) of every clip on each character; developer check, read-only ISO."""
    from pathlib import Path
    import numpy as np
    from PIL import Image, ImageDraw
    ma = _developer_module('model_assets')
    an = _developer_module('model_animations')

    def matrix(q):
        x, y, z, w = q
        return np.array([[1-2*(y*y+z*z), 2*(x*y-z*w), 2*(x*z+y*w), 0], [2*(x*y+z*w), 1-2*(x*x+z*z), 2*(y*z-x*w), 0],
                         [2*(x*z-y*w), 2*(y*z+x*w), 1-2*(x*x+y*y), 0], [0, 0, 0, 1]], dtype=np.float64)

    def posed(asset, pose):
        world, remaining = {}, {b.native_id: b for b in asset.bones}
        leg = sum(float(np.linalg.norm(remaining[b].bind_translation)) for b in (10, 11) if b in remaining)
        while remaining:
            for key, bone in list(remaining.items()):
                if bone.parent_id in remaining: continue
                t = pose.get(key)
                local = matrix(t.rotation) if t else np.eye(4)
                local[:3, 3] = bone.bind_translation
                if key == 2 and t and t.translation is not None:
                    local[:3, 3] += np.asarray(t.translation)*leg
                world[key] = world.get(bone.parent_id, np.eye(4)) @ local
                del remaining[key]
        pos = np.column_stack((asset.positions, np.ones(len(asset.positions))))
        out = np.zeros((len(pos), 3))
        for bone in asset.bones:
            m = world[bone.native_id] @ np.linalg.inv(bone.bind_world)
            weight = np.sum(np.where(asset.bone_indices == bone.native_id, asset.bone_weights, 0), axis=1)
            mask = weight > 0
            if np.any(mask): out[mask] += (pos[mask] @ m.T)[:, :3]*weight[mask, None]
        return out

    def tile(asset, verts, view, size, scale, center, label):
        img = Image.new('RGB', (size, size), (235, 235, 235))
        d = ImageDraw.Draw(img)
        u, w, depth = ((verts[:, 2], verts[:, 1], verts[:, 0]) if view == 'side' else
                       (verts[:, 0], verts[:, 1], verts[:, 2]))
        px, py = (u - center[0])*scale + size/2, (w - center[1])*scale + size/2
        tri = asset.triangles
        for t in np.argsort(depth[tri].mean(axis=1)):
            a, b, c = tri[t]
            n = np.cross(verts[b] - verts[a], verts[c] - verts[a]); ln = np.linalg.norm(n)
            shade = 0.4 + 0.6*abs(n[0 if view == 'side' else 2]/ln) if ln > 1e-9 else 0.5
            col = int(60 + 150*shade)
            d.polygon([(px[a], py[a]), (px[b], py[b]), (px[c], py[c])], fill=(col, col - 20, col - 40))
        ground = (0 - center[1])*scale + size/2
        d.line([(0, ground), (size, ground)], fill=(200, 40, 40))
        d.text((3, 3), label, fill=(0, 0, 0))
        return img

    out_dir = Path(out_dir); out_dir.mkdir(parents=True, exist_ok=True)
    clips = build_set()
    written = []
    for ch in characters:
        asset = ma.load_character(iso, ch)
        bind = posed(asset, {})
        height = float(np.percentile(np.abs(bind[:, 1]), 99.5)) or 1.0
        scale = size*0.45*zoom/height
        rows = []
        for key in keys or [(RUN, a) for a in IDS] + [(WALK, a) for a in range(2, 8)]:
            clip = an.AnimationClip.from_decoded(key[1], an.decompress_animation(clips[key]))
            for view in views:
                tiles = []
                for k in range(columns):
                    t = clip.frame_count*k/(columns - 1)
                    verts = posed(asset, clip.evaluate(t))
                    label = f'c{ch} {GAITS[key[0]]} {key[1]} t{t:.1f}/{clip.frame_count} {view}'
                    tiles.append(tile(asset, verts, view, size, scale, (0.0, -height*0.5), label))
                row = Image.new('RGB', (size*columns, size), (255, 255, 255))
                for i, img in enumerate(tiles): row.paste(img, (size*i, 0))
                rows.append(row)
        for part in range(0, len(rows), 16):
            chunk = rows[part:part + 16]
            sheet = Image.new('RGB', (size*columns, size*len(chunk)), (255, 255, 255))
            for i, row in enumerate(chunk): sheet.paste(row, (0, size*i))
            path = out_dir/f'ground-clips-c{ch}-{part//16}.png'
            sheet.save(path)
            written.append(str(path))
    return written


