def key_times(frames, keys=KEYS):
    return tuple(int(math.floor(k*frames/(keys - 1) + .5)) for k in range(keys))


def walk_like(gait):
    return gait in WALKING


def pose_at(gait, anim, t):
    """Deltas of clip (gait, anim) at time t (60 Hz units)."""
    if anim in TURNED:
        base, sign = TURNED[anim]
        return turned(pose_at(gait, base, t), sign)
    frames = FRAMES[(gait, anim)]
    if gait == STOP and anim in (8, 9):
        return stop_pose(min(1.0, t/frames))
    if anim == 3:
        return gait_pose(gait, (t % frames)/frames)
    if anim == 8:
        return gait_pose(WALK, (t % frames)/frames)
    if anim == 9:
        return gait_pose(WALK, (1.0 - (t % frames)/frames) % 1.0)
    if anim in SIDESTEP:
        return sidestep_pose(SIDESTEP[anim], (t % frames)/frames)
    if anim == 2:
        u = t/frames
        if walk_like(gait):
            phase = (0.5 + 0.5*u) % 1.0
        else:
            phase = u % 1.0
        amp = 1.0 if t >= frames else 0.35 + 0.65*smooth(u)
        return gait_pose(gait, phase, amp)
    raise KeyError(anim)


def encode_clip(frames, tracks, root=None, root_tag=0):
    """Decoded native clip bytes. tracks: {bone: [(time, quaternion), ...]} (one key = constant)."""
    body = bytearray()
    offsets = [0]*BONES
    base = 6 + 2*BONES
    for bone in sorted(tracks):
        keys = tracks[bone]
        offsets[bone] = (base + len(body))//4
        if bone == 2 and root is not None:
            body += struct.pack('<HH', root_tag, len(root))
            for t, xyz in root:
                body += struct.pack('<3fIQ', *xyz, t, encode_quat(keys[0][1]))
            continue
        body += struct.pack('<HH', 1, len(keys))
        for _, q in keys: body += struct.pack('<Q', encode_quat(q))
        if len(keys) > 1:
            for t, _ in keys: body += struct.pack('<H', t)
        while len(body) % 4: body += b'\0'
    return struct.pack('<HH', FLAGS, frames) + b'\0\0' + struct.pack(f'<{BONES}H', *offsets) + bytes(body)


def compress_literal(decoded):
    out = bytearray()
    for i in range(0, len(decoded), 32767):
        chunk = decoded[i:i + 32767]
        out += bytes((0xFE, 0x7F, 0xFE, 0xFF)) + struct.pack('>H', len(chunk)) + chunk
    return struct.pack('<II', len(decoded), len(out)) + bytes(out)


def decompress_literal(packed):
    """Read our literal-only streams without importing the model preview tools."""
    size, length = struct.unpack_from('<II', packed)
    if length != len(packed)-8:
        raise ValueError('Invalid ground clip packed length')
    out, pos = bytearray(), 8
    while pos < len(packed):
        if packed[pos:pos+4] != bytes((0xFE, 0x7F, 0xFE, 0xFF)) or pos+6 > len(packed):
            raise ValueError('Invalid ground clip literal chunk')
        count = struct.unpack_from('>H', packed, pos+4)[0]
        pos += 6
        if not count or pos+count > len(packed):
            raise ValueError('Truncated ground clip literal chunk')
        out.extend(packed[pos:pos+count]); pos += count
    if len(out) != size:
        raise ValueError('Invalid ground clip decoded length')
    return bytes(out)


def canonical(gait, anim, profile='male', style='classic'):
    if profile not in ('male', 'female') or style not in ground_motion.STYLES:
        raise ValueError('Invalid ground motion profile')
    if gait == STOP:
        gait = RUN
    gait = WALK if gait in WALKING else RUN
    if anim in (8, 9):
        gait = WALK
    if gait == RUN or style != 'classic':
        profile = 'male'
    return gait, anim, profile


def authored_pose(gait, anim, t, profile='male', style='classic'):
    """Approved local rotations and leg-normalized hip motion at native time t.

Native start clips use the same continuous cycle as their loop. The game's
existing blend and our movement ramp ease the entry without distorting knees.
"""
    frames = FRAMES[(gait, anim)]
    gait, anim, profile = canonical(gait, anim, profile, style)
    base, turn = TURNED.get(anim, (anim, 0))
    phase = (t/frames) % 1.
    if base == 9:
        phase = (-phase) % 1.
    root, pose = ground_motion.sample('walk' if gait == WALK else 'run', phase, profile, style)
    if turn:
        for bone, angle in TURN.items():
            pose[bone] = qnorm(qmul(qaxis((0, 1, 0), turn*angle), pose[bone]))
    return root, pose


def motion_tag(gait, anim, profile, style='classic'):
    gait, anim, profile = canonical(gait, anim, profile, style)
    anim = TURNED.get(anim, (anim, 0))[0]
    # Starts and loops have the same root curve. Aliases use one immutable row.
    if anim == 2:
        anim = 3
    return 0x4000 + 2*(1 + (40 if profile == 'female' else 0) + gait*10 + anim-2)


def decoded_clip(gait, anim, profile='male', style='classic'):
    frames = FRAMES[(gait, anim)]
    authored = not (gait == STOP and anim in (8, 9)) and anim not in SIDESTEP
    # Preserve brake and sideways clip bytes exactly. Forward/backward motion
    # gets one quaternion sample per native unit (with native interpolation).
    keys = frames+1 if authored else (STOP_KEYS if gait == STOP else 17)
    times = key_times(frames, keys)
    if authored:
        samples = [authored_pose(gait, anim, t, profile, style) for t in times]
        poses = [p for _, p in samples]
        root = [(t, xyz) for t, (xyz, _) in zip(times, samples)]
    else:
        poses = [local_rotations(pose_at(gait, anim, t)) for t in times]
        root = None
    tracks = {}
    for bone in TRACKED:
        keys = [(t, p[bone]) for t, p in zip(times, poses)]
        packed = {encode_quat(q) for _, q in keys}
        tracks[bone] = keys[:1] if len(packed) == 1 else keys
    return encode_clip(frames, tracks, root, motion_tag(gait, anim, profile, style) if authored else 0)


@functools.lru_cache(maxsize=6)
def _built_set(profile, style):
    """{(set, anim): native clip bytes (8-byte size header + literal byte-pair stream)} for the five sets and anims
    2..11; SHARED entries are the very same bytes object as their source (one copy in RAM)."""
    out = {}
    for gait in SETS + (STOP,):
        for anim in IDS:
            key = (gait, anim)
            if key in SHARED: continue
            out[key] = compress_literal(decoded_clip(gait, anim, profile, style))
    for key, source in SHARED.items(): out[key] = out[source]
    return tuple(out.items())


def build_set(profile='male', style='classic'):
    """An independent directory of cached immutable clip bytes for this profile."""
    return dict(_built_set(profile, style))


