def beta36_image(adapter):
    """The beta.35/36 gate image of this adapter, or None for an adapter those releases did not ship."""
    text = _HEX.get(adapter)
    if text is None:
        return None
    image = bytes.fromhex(text)
    if hashlib.sha256(image).hexdigest() != SHA256[adapter]:
        raise ValueError(f'The frozen beta.36 dispatch gate for {adapter} is damaged')
    return image
