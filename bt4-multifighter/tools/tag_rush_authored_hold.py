def _qnorm(value):
    norm = math.sqrt(sum(x*x for x in value))
    if not all(math.isfinite(x) for x in value) or norm < 1e-8:
        raise ValueError('Invalid authored hold rotation')
    return tuple(x/norm for x in value)


def nlerp(first, second, weight):
    first, second = _qnorm(first), _qnorm(second)
    sign = -1. if sum(a*b for a,b in zip(first, second)) < 0. else 1.
    return _qnorm(tuple(a + (sign*b-a)*weight for a,b in zip(first, second)))


def select(shoulder_ratio):
    if not math.isfinite(shoulder_ratio) or shoulder_ratio <= 0.:
        raise ValueError('Invalid authored hold body dimensions')
    anchors = tuple(t['shoulder_ratio'] for t in TEMPLATES)
    first = 0 if shoulder_ratio <= anchors[1] else 1
    weight = max(0., min(1., (shoulder_ratio-anchors[first]) /
                        (anchors[first+1]-anchors[first])))
    return first, first+1, weight


def endpoint(shoulder_ratio):
    first, second, weight = select(shoulder_ratio)
    result = dict(source_sha256=SOURCE_SHA256,
                  templates=(TEMPLATES[first]['name'], TEMPLATES[second]['name']),
                  weight=weight, actors={})
    for role in ('holder', 'victim'):
        a,b = TEMPLATES[first][role], TEMPLATES[second][role]
        result['actors'][role] = dict(
            root_translation=tuple(x+(y-x)*weight for x,y in zip(a['root_translation'], b['root_translation'])),
            rotations={joint:nlerp(a['rotations'][index], b['rotations'][index], weight)
                       for index,joint in enumerate(JOINTS)})
    return result


def motion(shoulder_ratio, elapsed):
    if not math.isfinite(elapsed):raise ValueError('Invalid authored hold clock')
    first,second,body_weight=select(shoulder_ratio)
    banks=(*MOTION_TEMPLATES,TEMPLATES)
    segment=next((index for index,end in enumerate(KEYFRAMES[1:]) if elapsed<end),2)
    clock=max(0.,min(1.,(elapsed-KEYFRAMES[segment])/(KEYFRAMES[segment+1]-KEYFRAMES[segment])))
    clock=clock*clock*(3.-2.*clock)
    result=dict(source_sha256=SOURCE_SHA256,templates=(TEMPLATES[first]['name'],TEMPLATES[second]['name']),
                weight=body_weight,segment=segment,motion_weight=clock,actors={})
    for role in('holder','victim'):
        mixed=[]
        for bank in(banks[segment],banks[segment+1]):
            a,b=bank[first][role],bank[second][role]
            mixed.append(dict(root_translation=tuple(x+(y-x)*body_weight for x,y in zip(a['root_translation'],b['root_translation'])),
                rotations={joint:nlerp(a['rotations'][index],b['rotations'][index],body_weight)for index,joint in enumerate(JOINTS)}))
        a,b=mixed
        result['actors'][role]=dict(root_translation=tuple(x+(y-x)*clock for x,y in zip(a['root_translation'],b['root_translation'])),
            rotations={joint:nlerp(a['rotations'][joint],b['rotations'][joint],clock)for joint in JOINTS})
    return result


def data():
    banks=(TEMPLATES,*MOTION_TEMPLATES)
    if len(banks)!=4 or len(JOINTS)!=33 or any(len(bank)!=3 for bank in banks):
        raise ValueError('Incomplete authored hold templates')
    out=bytearray(HEADER+STRIDE*3*len(banks))
    struct.pack_into('<4I',out,0,MAGIC,VERSION,3,STRIDE)
    out[16:48]=bytes.fromhex(SOURCE_SHA256)
    struct.pack_into('<4I',out,48,len(JOINTS),len(banks),STRIDE*3,ACQUISITION_FRAMES)
    for bank_index,bank in enumerate(banks):
        previous=0.
        for index,template in enumerate(bank):
            at=HEADER+STRIDE*(bank_index*3+index)
            ratio=template['shoulder_ratio']
            if not math.isfinite(ratio)or not previous<ratio<10.:
                raise ValueError('Invalid authored hold template ordering')
            previous=ratio;struct.pack_into('<f',out,at,ratio)
            for role,offset in(('holder',HOLDER_ROOT),('victim',VICTIM_ROOT)):
                row=template[role]
                if len(row['rotations'])!=len(JOINTS)or any(not math.isfinite(v)or abs(v)>100. for v in row['root_translation']):
                    raise ValueError('Invalid authored hold template')
                struct.pack_into('<3f',out,at+offset,*row['root_translation'])
                role_offset=0 if role=='holder'else len(JOINTS)*16
                for joint_index,q in enumerate(row['rotations']):
                    struct.pack_into('<4f',out,at+ROTATIONS+role_offset+16*joint_index,*_qnorm(q))
    if DATA+len(out)>END:raise ValueError('Authored hold endpoints exceed reserved storage')
    return bytes(out)


def receipt():
    payload=data()
    return dict(source_sha256=SOURCE_SHA256, payload_sha256=hashlib.sha256(payload).hexdigest(),
                template_names=tuple(t['name'] for t in TEMPLATES), keyframes=KEYFRAMES,
                upper_body_joints=JOINTS, address=DATA, bytes=len(payload))


def pieces():
    return [(DATA, data())]
